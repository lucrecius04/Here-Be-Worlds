/** Localized game / card copy — `cs` default; missing `en` falls back to `cs`. */
export function t(value: LocalizedString, locale: Locale = DEFAULT_LOCALE): string {
  if (locale === 'cs') return value.cs ?? value.en ?? '';
  return value.en ?? value.cs ?? '';
}

